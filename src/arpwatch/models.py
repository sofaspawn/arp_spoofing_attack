"""Shared data models and utilities for ARP Spoofing Detection System."""
from __future__ import annotations
from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone
from enum import Enum
from typing import Optional, Dict, List, Any
import json
import time
import uuid


class ArpOperation(Enum):
    REQUEST = 1
    REPLY = 2


class AlertSeverity(Enum):
    INFO = "info"
    WARNING = "warning"
    CRITICAL = "critical"


class AlertType(Enum):
    MAPPING_CHANGE = "mapping_change"
    DUPLICATE_MAPPING = "duplicate_mapping"
    REPLY_RATE_EXCEEDED = "reply_rate_exceeded"
    GRATUITOUS_ARP_FLOOD = "gratuitous_arp_flood"
    MAC_SPOOFING = "mac_spoofing"
    GATEWAY_IMPERSONATION = "gateway_impersonation"
    TWO_WAY_SPOOFING = "two_way_spoofing"
    BASELINE_VIOLATION = "baseline_violation"


@dataclass
class ArpPacket:
    """Represents a captured ARP packet."""
    timestamp: float
    operation: ArpOperation
    sender_ip: str
    sender_mac: str
    target_ip: str
    target_mac: str
    is_gratuitous: bool = False
    packet_id: str = field(default_factory=lambda: str(uuid.uuid4())[:8])
    
    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d['operation'] = self.operation.name
        d['timestamp_iso'] = datetime.fromtimestamp(self.timestamp, timezone.utc).isoformat()
        return d
    
    @classmethod
    def from_scapy(cls, pkt) -> 'ArpPacket':
        """Create from Scapy ARP packet."""
        from scapy.layers.l2 import ARP
        arp = pkt[ARP]
        op = ArpOperation.REQUEST if arp.op == 1 else ArpOperation.REPLY
        is_grat = arp.psrc == arp.pdst and arp.op == 2
        return cls(
            timestamp=pkt.time,
            operation=op,
            sender_ip=arp.psrc,
            sender_mac=arp.hwsrc.lower(),
            target_ip=arp.pdst,
            target_mac=arp.hwdst.lower(),
            is_gratuitous=is_grat
        )


@dataclass
class IpMacBinding:
    """Represents a learned IP-to-MAC binding."""
    ip: str
    mac: str
    first_seen: float
    last_seen: float
    seen_count: int = 1
    is_gateway: bool = False
    is_static: bool = False
    confidence: float = 1.0
    
    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d['first_seen_iso'] = datetime.fromtimestamp(self.first_seen, timezone.utc).isoformat()
        d['last_seen_iso'] = datetime.fromtimestamp(self.last_seen, timezone.utc).isoformat()
        return d
    
    def update(self, timestamp: float, confidence: float = 1.0):
        self.last_seen = timestamp
        self.seen_count += 1
        self.confidence = min(1.0, self.confidence + 0.1)


@dataclass
class Alert:
    """Security alert generated by detection engine."""
    alert_id: str
    timestamp: float
    alert_type: AlertType
    severity: AlertSeverity
    sender_ip: str
    sender_mac: str
    target_ip: str
    previous_mac: Optional[str]
    message: str
    details: Dict[str, Any] = field(default_factory=dict)
    mitigated: bool = False
    mitigation_action: Optional[str] = None
    
    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d['alert_type'] = self.alert_type.value
        d['severity'] = self.severity.value
        d['timestamp_iso'] = datetime.fromtimestamp(self.timestamp, timezone.utc).isoformat()
        return d
    
    @classmethod
    def create(cls, alert_type: AlertType, severity: AlertSeverity, 
               sender_ip: str, sender_mac: str, target_ip: str,
               previous_mac: Optional[str], message: str, **details) -> 'Alert':
        return cls(
            alert_id=str(uuid.uuid4())[:8],
            timestamp=time.time(),
            alert_type=alert_type,
            severity=severity,
            sender_ip=sender_ip,
            sender_mac=sender_mac,
            target_ip=target_ip,
            previous_mac=previous_mac,
            message=message,
            details=details
        )


